import { readdir, readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
async function walk(dir) {
  const items = await readdir(dir, { withFileTypes: true });
  return (
    await Promise.all(
      items.map((item) =>
        item.isDirectory()
          ? walk(dir + "/" + item.name)
          : dir + "/" + item.name,
      ),
    )
  ).flat();
}
const version = JSON.parse(await readFile("package.json", "utf8")).version;
const assets = [
  "index.html",
  "manifest.webmanifest",
  ...(await walk("css")).filter((p) => p.endsWith(".css")),
  ...(await walk("js")).filter((p) => p.endsWith(".js")),
  ...(await walk("assets/icons")),
].sort();
const hash = createHash("sha256");
for (const asset of assets) hash.update(await readFile(asset));
const cache = "v" + version + "-" + hash.digest("hex").slice(0, 12);
const source = `// Generated by npm run build:sw. Cache only the allowlisted static application shell.
const CACHE_VERSION = "${cache}";
const CACHE_PREFIX = "devkit-shell-" + encodeURIComponent(new URL(self.registration.scope).pathname) + "-";
const CACHE_NAME = CACHE_PREFIX + CACHE_VERSION;
const ASSETS = ${JSON.stringify(assets, null, 2)};
const URLS=ASSETS.map(path=>new URL(path,self.registration.scope).href);
self.addEventListener('install',event=>event.waitUntil(caches.open(CACHE_NAME).then(cache=>cache.addAll(URLS))));
self.addEventListener('activate',event=>event.waitUntil((async()=>{for(const key of await caches.keys())if(key.startsWith(CACHE_PREFIX)&&key!==CACHE_NAME)await caches.delete(key);await self.clients.claim();})()));
self.addEventListener('message',event=>{if(event.data?.type==='SKIP_WAITING')self.skipWaiting();});
self.addEventListener('fetch',event=>{const request=event.request;if(request.method!=='GET')return;const url=new URL(request.url);if(url.origin!==self.location.origin||url.search)return;const scope=new URL(self.registration.scope);const navigation=request.mode==='navigate'&&(url.pathname===scope.pathname||url.pathname===scope.pathname+'index.html');if(!navigation&&!URLS.includes(url.href))return;const key=navigation?new URL('index.html',scope).href:url.href;event.respondWith(caches.open(CACHE_NAME).then(async cache=>{const cached=await cache.match(key);if(cached)return cached;return fetch(request);}));});
`;
await writeFile("sw.js", source);
console.log("Versioned shell: " + cache + " · " + assets.length + " assets");
